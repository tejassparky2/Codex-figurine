"""Rebuild improvements/INDEX.md from the front matter of every proposal."""
from pathlib import Path

here = Path(__file__).resolve().parent
rows = []
for f in sorted(here.glob('20*.md')):
    lines = f.read_text(encoding='utf-8').splitlines()
    meta = {}
    if lines and lines[0].strip() == '---':
        for line in lines[1:]:
            if line.strip() == '---':
                break
            key, _, value = line.partition(':')
            meta[key.strip()] = value.strip()
    trials = sum(1 for line in lines if line.startswith('| 20'))
    rows.append((meta.get('date', ''), meta.get('status', '?'), meta.get('author', '?'), meta.get('title', f.stem),
                 meta.get('applies_to', ''), trials, f.name))
order = {'proposed': 0, 'confirmed': 1, 'adopted': 2, 'rejected': 3, 'superseded': 4}
rows.sort(key=lambda r: (order.get(r[1], 9), r[0]), reverse=False)
out = ['# Improvements index', '', 'Generated by `python improvements/index.py`. Read every `proposed` entry before your next job, and add your trial.', '',
       '| Status | Date | Author | Improvement | Applies to | Trials by others |', '|---|---|---|---|---|---:|']
out += [f'| {s} | {d} | {a} | [{t}]({n}) | {ap} | {tr} |' for d, s, a, t, ap, tr, n in rows]
(here / 'INDEX.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'{len(rows)} improvements indexed')
